    RAW_FORMAT,
    RAW_DIGEST,
    REPEATED_SOURCE_KEY,
    CONFLICTING_SOURCE_KEY,
    SOURCE_INCOMPLETE,
    RELATION_UNAVAILABLE,
    AMBIGUOUS_RELATION,
